#!/usr/bin/env python3
"""Generate backing-vocal pitches with an OpenAI Responses API model.

The model only chooses a semitone offset for every canonical lead note. Timing,
lyrics, legato metadata, and note identity remain deterministic in the app.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
from typing import Any, Callable

from backing_vocal_music import (
    build_beat_map,
    build_windows,
    chord_at,
    finalize_generated_notes,
    flatten_note_windows,
    harmonic_postprocess,
    midi_to_pitch,
    normalize_chords,
    normalize_lead,
    normalize_tempos,
    stitch_notes,
    style_by_id,
    style_requirements,
    write_debug_dsl,
)


OPENAI_RESPONSES_URL = "https://api.openai.com/v1/responses"
SUPPORTED_MODELS = {"gpt-5.6-luna", "gpt-5.6-terra"}
KEYCHAIN_SERVICE = "com.syntheticobsidian.openai"
KEYCHAIN_ACCOUNT = "synthetic-obsidian"


def generate_with_openai(
    request: dict[str, Any],
    args: Any,
    model: str,
    stream_callback: Callable[[dict[str, Any]], None] | None = None,
) -> dict[str, Any]:
    if model not in SUPPORTED_MODELS:
        raise ValueError(f"Unsupported OpenAI backing-vocal model: {model}")

    style = style_by_id(str(request.get("style_id", "")))
    if style is None:
        raise ValueError(f"Unknown backing-vocal style: {request.get('style_id')}")

    duration = float(request.get("duration") or 0.0)
    fallback_bpm = float(request.get("bpm") or 120.0)
    tempos = normalize_tempos(request.get("tempo_segments"), fallback_bpm, duration)
    beat_map = build_beat_map(tempos)
    lead = normalize_lead(request.get("lead_notes"), beat_map)
    chords = normalize_chords(request.get("chords"), beat_map)
    if not lead or not chords:
        raise ValueError("OpenAI generation needs lead notes and chords")

    max_notes = max(1, min(64, int(getattr(args, "max_lead_notes", 48))))
    max_gap = float(getattr(args, "max_gap_beats", 2.0))
    windows = build_windows(lead, max_notes, max_gap)
    api_key = load_api_key()
    generated_sets: list[list[dict[str, Any]]] = []

    for window_index, window in enumerate(windows, start=1):
        notes = predict_window(request, style, window, chords, model, api_key)
        generated_sets.append(notes)
        if stream_callback is not None:
            stream_callback(
                {
                    "type": "window",
                    "engine": "openai_responses",
                    "model": model,
                    "style_id": style["id"],
                    "style_name": style["name"],
                    "window_index": window_index,
                    "window_count": len(windows),
                    "note_count": sum(len(items) for items in generated_sets),
                    "warnings": [],
                    "notes": finalize_generated_notes(
                        generated_sets,
                        style,
                        chords,
                        str(request.get("key") or "C major"),
                        beat_map,
                    ),
                }
            )

    corrected = harmonic_postprocess(
        flatten_note_windows(generated_sets),
        chords,
        str(request.get("key") or "C major"),
        style["id"],
    )
    debug_path = write_debug_dsl(
        request,
        style,
        chords,
        lead,
        [corrected],
        [f"Generated by OpenAI Responses API model {model} with harmonic validation."],
    )
    notes = stitch_notes([corrected], style, beat_map)
    return {
        "engine": "openai_responses",
        "model": model,
        "style_id": style["id"],
        "style_name": style["name"],
        "window_count": len(windows),
        "note_count": len(notes),
        "warnings": [],
        "debug_dsl_path": str(debug_path) if debug_path else "",
        "notes": notes,
    }


def predict_window(
    request: dict[str, Any],
    style: dict[str, str],
    lead: list[dict[str, Any]],
    chords: list[dict[str, Any]],
    model: str,
    api_key: str,
) -> list[dict[str, Any]]:
    note_context = []
    for note in lead:
        active_chord = chord_at(chords, float(note["start"]))
        note_context.append(
            {
                "id": note["id"],
                "midi_note": int(note["midi_note"]),
                "pitch": note["pitch"],
                "start_beat": float(note["start"]),
                "duration_beats": float(note["duration"]),
                "bar": int(note["bar"]),
                "beat": float(note["beat"]),
                "phrase_id": note["phrase_id"],
                "syllable": note.get("syllable"),
                "legato_from_previous": bool(note.get("legato_from_previous")),
                "legato_to_next": bool(note.get("legato_to_next")),
                "chord": active_chord.get("chord", "N"),
                "chord_tones": active_chord.get("notes", []),
            }
        )

    references = [str(note["id"]) for note in lead]
    schema = {
        "type": "object",
        "properties": {
            "notes": {
                "type": "array",
                "minItems": len(lead),
                "maxItems": len(lead),
                "items": {
                    "type": "object",
                    "properties": {
                        "source_lead_ref": {"type": "string", "enum": references},
                        "semitone_offset": {"type": "integer", "minimum": -24, "maximum": 24},
                    },
                    "required": ["source_lead_ref", "semitone_offset"],
                    "additionalProperties": False,
                },
            }
        },
        "required": ["notes"],
        "additionalProperties": False,
    }
    musical_input = {
        "style": style,
        "style_requirement": style_requirements(style["id"]),
        "key": str(request.get("key") or "C major"),
        "meter": _request_meter(request),
        "lead_notes": note_context,
    }
    instructions = (
        "You are an expert vocal arranger. Compose one coherent backing-vocal phrase. "
        "Return exactly one unique output item for every input lead-note id, in the same order. "
        "Only choose semitone offsets; never change rhythm or ids. Respect the requested style, "
        "active chord, key, singable range, smooth voice leading, and phrase-level musical shape. "
        "Avoid a constant pitch or constant interval unless the requested style explicitly calls for it. "
        "For contrary/oblique/dynamic counterpoint, make the requested motion audible rather than merely "
        "copying the lead. Output JSON matching the supplied schema and nothing else."
    )
    payload = {
        "model": model,
        "instructions": instructions,
        "input": json.dumps(musical_input, ensure_ascii=False, separators=(",", ":")),
        "reasoning": {"effort": "low"},
        "text": {
            "verbosity": "low",
            "format": {
                "type": "json_schema",
                "name": "backing_vocal_offsets",
                "strict": True,
                "schema": schema,
            },
        },
        "max_output_tokens": max(1200, len(lead) * 48),
        "store": False,
    }
    response = _post_json(OPENAI_RESPONSES_URL, payload, api_key)
    parsed = json.loads(_response_output_text(response))
    returned = parsed.get("notes") if isinstance(parsed, dict) else None
    if not isinstance(returned, list):
        raise RuntimeError("OpenAI response did not contain a notes array")

    offsets: dict[str, int] = {}
    for item in returned:
        if not isinstance(item, dict):
            continue
        reference = str(item.get("source_lead_ref") or "")
        if reference not in references or reference in offsets:
            continue
        offsets[reference] = max(-24, min(24, int(item.get("semitone_offset") or 0)))
    missing = [reference for reference in references if reference not in offsets]
    if missing:
        raise RuntimeError(
            f"OpenAI model omitted {len(missing)} of {len(references)} lead-note references"
        )

    output = []
    for index, source in enumerate(lead, start=1):
        offset = offsets[str(source["id"])]
        midi = max(24, min(96, int(source["midi_note"]) + offset))
        output.append(
            {
                "id": f"{style['id'].lower()}_openai_{index:04d}",
                "part": "backing",
                "strategy": style["id"].lower(),
                "start": float(source["start"]),
                "duration": max(0.05, float(source["duration"])),
                "midi_note": midi,
                "pitch": midi_to_pitch(midi),
                "velocity": 74,
                "lyric": source.get("syllable") or "",
                "syllable_id": source.get("syllable_id") or "",
                "legato_from_previous": bool(source.get("legato_from_previous")),
                "legato_to_next": bool(source.get("legato_to_next")),
                "melisma_continuation": bool(source.get("melisma_continuation")),
                "source_lead_ref": source["id"],
            }
        )
    return output


def load_api_key() -> str:
    value = os.environ.get("OPENAI_API_KEY", "").strip()
    if value:
        return value
    if sys.platform == "darwin":
        result = subprocess.run(
            [
                "/usr/bin/security",
                "find-generic-password",
                "-w",
                "-a",
                KEYCHAIN_ACCOUNT,
                "-s",
                KEYCHAIN_SERVICE,
            ],
            check=False,
            capture_output=True,
            text=True,
            timeout=5,
        )
        value = result.stdout.strip()
        if result.returncode == 0 and value:
            return value
    raise RuntimeError(
        "OpenAI API key is unavailable. Set OPENAI_API_KEY or save it in the Synthetic Obsidian keychain entry."
    )


def _request_meter(request: dict[str, Any]) -> str:
    signatures = request.get("time_signatures")
    if isinstance(signatures, list) and signatures and isinstance(signatures[0], dict):
        numerator = int(signatures[0].get("numerator") or 4)
        denominator = int(signatures[0].get("denominator") or 4)
        return f"{numerator}/{denominator}"
    return str(request.get("meter") or "4/4")


def _post_json(url: str, payload: dict[str, Any], api_key: str) -> dict[str, Any]:
    request = urllib.request.Request(
        url,
        data=json.dumps(payload, ensure_ascii=False).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=180) as response:
            return json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", errors="replace")[:2000]
        raise RuntimeError(f"OpenAI API returned HTTP {exc.code}: {body}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"Could not reach OpenAI API: {exc.reason}") from exc


def _response_output_text(response: dict[str, Any]) -> str:
    direct = response.get("output_text")
    if isinstance(direct, str) and direct.strip():
        return direct
    for item in response.get("output", []):
        if not isinstance(item, dict) or item.get("type") != "message":
            continue
        for content in item.get("content", []):
            if isinstance(content, dict) and content.get("type") == "output_text":
                text = content.get("text")
                if isinstance(text, str) and text.strip():
                    return text
    error = response.get("error")
    if error:
        raise RuntimeError(f"OpenAI response failed: {error}")
    raise RuntimeError("OpenAI response did not contain output text")
